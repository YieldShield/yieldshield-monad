/** Re-run imported regression suites with Base modular deployments. Originals stay unchanged. */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const root=resolve(dirname(fileURLToPath(import.meta.url)), '..');
const out=resolve(root,'contracts/test/base-modules');
mkdirSync(out,{recursive:true});
const files=['SplitRiskPoolAccounting.t.sol','SplitRiskPoolFactory.t.sol','SplitRiskPoolCommission.t.sol','SplitRiskPoolCrossAssetFees.t.sol','SplitRiskPoolProtectorWithdrawalCallbacks.t.sol'];
for(const file of files) {
 let s=readFileSync(resolve(root,'contracts/test',file),'utf8');
 s=s.replace(/from "\.\.\//g,'from "../../').replace(/from "\.\/helpers\//g,'from "../helpers/');
 s=s.replace('from "../helpers/FactoryProxyTestBase.sol"','from "./BaseFactoryProxyTestBase.sol"');
 s=s.replace(/new SplitRiskPool\(\)/g,'SplitRiskPool(payable(BaseModuleTestDeploy.pool(vm)))');
 s=s.replace(/new SplitRiskPoolFactory\(\)/g,'SplitRiskPoolFactory(payable(BaseModuleTestDeploy.factory(vm)))');
 s=s.replace(/contract (\w+Test) is/g,'contract Base$1 is');
 s=s.replace('pragma solidity ^0.8.35;','pragma solidity ^0.8.35;\nimport { BaseModuleTestDeploy } from "./BaseModuleTestDeploy.sol";');
 writeFileSync(resolve(out,'Base'+file),'// GENERATED by scripts/generate-base-parity-tests.mjs.\n'+s);
}
let helper=readFileSync(resolve(root,'contracts/test/helpers/FactoryProxyTestBase.sol'),'utf8');
helper=helper.replace('from "./TestTimelockHelper.sol"','from "../helpers/TestTimelockHelper.sol"');
helper=helper.replace('new SplitRiskPoolFactory()','SplitRiskPoolFactory(payable(BaseModuleTestDeploy.factory(Vm(0x7109709ECfa91a80626fF3989D68f67F5b1DD12D))))');
helper=helper.replace('pragma solidity ^0.8.35;','pragma solidity ^0.8.35;\nimport { BaseModuleTestDeploy } from "./BaseModuleTestDeploy.sol";\nimport { Vm } from "forge-std/Vm.sol";');
writeFileSync(resolve(out,'BaseFactoryProxyTestBase.sol'),'// GENERATED by scripts/generate-base-parity-tests.mjs.\n'+helper);
console.log('Generated 5 original regression suites using size-checked Base modular deployments.');
